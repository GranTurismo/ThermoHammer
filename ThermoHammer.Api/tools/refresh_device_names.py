#!/usr/bin/env python3
"""Rebuilds ThermoHammer.Api/ThermoHammer.Api/Data/play_devices.tsv: the table that turns the code an Android phone reports
(Build.MODEL, e.g. "VKP-NX9") into the name printed on its box ("HONOR 600 Pro").

Source: Google's public list of the devices Google Play supports (columns Retail Branding, Marketing Name, Device, Model),
https://storage.googleapis.com/play_public/supported_devices.csv. Google adds phones to it every few weeks, so run this
now and then, commit the new table and deploy:

    python3 ThermoHammer.Api/tools/refresh_device_names.py              # downloads the list (run from the repo root)
    python3 ThermoHammer.Api/tools/refresh_device_names.py --csv FILE   # uses a copy you already have

Fix a single wrong or missing name in Data/device_name_overrides.tsv instead of editing the generated table:
the overrides win and survive every refresh.
"""
import argparse, csv, datetime, io, pathlib, sys, urllib.request

URL = "https://storage.googleapis.com/play_public/supported_devices.csv"
OUT = pathlib.Path(__file__).resolve().parent.parent / "ThermoHammer.Api" / "Data" / "play_devices.tsv"


def read_rows(path):
    raw = pathlib.Path(path).read_bytes() if path else urllib.request.urlopen(URL, timeout=60).read()
    # Google publishes it as UTF-16 with a byte-order mark
    text = raw.decode("utf-16") if raw[:2] in (b"\xff\xfe", b"\xfe\xff") else raw.decode("utf-8-sig")
    rows = list(csv.reader(io.StringIO(text)))
    if [c.strip().lower() for c in rows[0]] != ["retail branding", "marketing name", "device", "model"]:
        sys.exit(f"unexpected columns in the list: {rows[0]}")
    return rows[1:]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--csv", help="a copy of supported_devices.csv; downloaded when left out")
    args = ap.parse_args()

    table = set()
    for brand, name, _device, model in read_rows(args.csv):
        brand, name, model = (" ".join(v.split()) for v in (brand, name, model))   # also removes tabs and line breaks
        # nothing to learn from a row without a name, or whose "name" is just the code again (e.g. "Pixel 8")
        if brand and name and model and name.lower() != model.lower():
            table.add((model.upper(), brand, name))
    if len(table) < 10_000:
        sys.exit(f"only {len(table)} usable rows: the list looks wrong, not writing anything")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="\n") as f:
        f.write("# Phone code -> marketing name, generated by tools/refresh_device_names.py from Google's Play supported-devices\n")
        f.write(f"# list ({URL}) on {datetime.date.today().isoformat()}. Do not edit by hand: put corrections in device_name_overrides.tsv.\n")
        f.write("# code<TAB>brand<TAB>name\n")
        for model, brand, name in sorted(table):
            f.write(f"{model}\t{brand}\t{name}\n")
    print(f"{len(table)} rows -> {OUT}")


if __name__ == "__main__":
    main()
